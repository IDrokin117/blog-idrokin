#!/usr/bin/env bash
# Site tests: build the site from tests/fixture/content and assert on the built output.
# Zola is located via $ZOLA, else `zola` on PATH. Run: tests/run.sh
set -u
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ZOLA="${ZOLA:-zola}"
command -v "$ZOLA" >/dev/null 2>&1 || { echo "zola not found; set \$ZOLA or install it (docs/development.md)"; exit 2; }

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
cp -r "$ROOT/config.toml" "$ROOT/templates" "$WORK/"
[ -d "$ROOT/sass" ] && cp -r "$ROOT/sass" "$WORK/"
[ -d "$ROOT/static" ] && cp -r "$ROOT/static" "$WORK/"
cp -r "$ROOT/tests/fixture/content" "$WORK/content"
OUT="$WORK/public"
if ! "$ZOLA" --root "$WORK" build --output-dir "$OUT" >"$WORK/build.log" 2>&1; then
  cat "$WORK/build.log"; echo "FAIL: build"; exit 1
fi

FAILS=0
pass() { echo "ok   - $1"; }
fail() { echo "FAIL - $1"; FAILS=$((FAILS+1)); }
has()    { grep -Eq -- "$2" "$OUT/$1" 2>/dev/null && pass "$3" || fail "$3"; }
lacks()  { grep -Eq -- "$2" "$OUT/$1" 2>/dev/null && fail "$3" || pass "$3"; }
exists() { [ -e "$OUT/$1" ] && pass "$2" || fail "$2"; }
absent() { [ -e "$OUT/$1" ] && fail "$2" || pass "$2"; }

# Menu: exactly Home, Posts, Resume
menu=$(tr -d '\n' <"$OUT/index.html" | grep -oE '<nav[^>]*>.*</nav>' | grep -oE '<a [^>]*>[^<]*</a>' | sed -E 's/<[^>]*>//g' | paste -sd,)
[ "$menu" = "Home,Posts,Resume" ] && pass "menu is Home,Posts,Resume" || fail "menu is Home,Posts,Resume (got: $menu)"

# Posts naming
has posts/index.html '<h1[^>]*>Posts</h1>' "posts section heading is Posts"
lacks index.html '>Notes<' "no Notes label on home"

# Post pages render; existing URL unchanged
has posts/hello-world/index.html '<h1[^>]*>Hello World</h1>' "existing post URL /posts/hello-world/ renders"
has posts/hello-world/index.html 'Hello body text' "post body rendered"
has posts/standalone/index.html '<h1[^>]*>Standalone Post</h1>' "post outside a series renders"
has posts/index.html 'href="?[^" >]*/posts/standalone/' "posts list links posts"

# Resume
has resume/index.html 'Fixture resume body' "resume page renders"
has resume/index.html 'href="?mailto:fixture@example.com[" >]' "resume shows email from front matter"
has resume/index.html 'href="?https://github.com/fixture[" >]' "resume shows GitHub from front matter"
has resume/index.html 'href="?https://www.linkedin.com/in/fixture/[" >]' "resume shows LinkedIn from front matter"
has resume/index.html 'Fixtureland' "resume shows location from front matter"
for h in Summary Experience Skills Education; do
  has resume/index.html "<h2[^>]*>$h</h2>" "resume renders $h section from markdown"
done
has resume/index.html '<a href="?[^" >]*/files/resume\.pdf"?[^>]*>Download PDF</a>' "resume has Download PDF link at stable URL"
has posts/hello-world/index.html '<img src="?[^" >]*/images/hello_world_meme\.jpg' "draw_image component renders in post"
absent files/resume.pdf "PDF is generated by the pipeline, not committed"
[ ! -e "$ROOT/static/files/resume.pdf" ] && pass "no committed resume.pdf" || fail "no committed resume.pdf"
{ ! grep -q 'download it in' "$ROOT/content/resume/_index.md"; } && pass "no stale PDF sentence in real resume" || fail "no stale PDF sentence in real resume"
# Real resume: single markdown source with contacts in front matter and the four sections
REAL="$ROOT/content/resume/_index.md"
for h in Summary Experience Skills Education; do
  grep -Eq "^## $h\s*$" "$REAL" && pass "real resume has $h heading" || fail "real resume has $h heading"
done
for k in email github linkedin location; do
  awk '/^\+\+\+/{n++} n==1' "$REAL" | grep -Eq "^$k *=" && pass "real resume front matter has $k" || fail "real resume front matter has $k"
done
{ ! grep -Eq '<(a|div|ul|section) ' "$REAL" 2>/dev/null; } && pass "real resume has no HTML markup" || fail "real resume has no HTML markup"

# Home page (links must be in the page body, not only in the header or footer)
home_main=$(tr -d '\n' <"$OUT/index.html" | grep -oE '<main[^>]*>.*</main>')
in_home() { printf '%s' "$home_main" | grep -Eq -- "$1" && pass "$2" || fail "$2"; }
has index.html '<h1[^>]*>Igor Drokin</h1>' "home shows the author name"
in_home '<img[^>]*avatar' "home shows an avatar"
in_home 'href="?[^" >]*/resume/?[" >]' "home links to Resume"
in_home 'href="?https://github\.com/[^" >]+' "home links to GitHub"
in_home 'href="?https://www\.linkedin\.com/[^" >]+' "home links to LinkedIn"
in_home 'href="?mailto:[^" >]+' "home links to Email"
home_posts=$(grep -oE 'href="?[^" >]*/posts/[a-z-]+/' "$OUT/index.html" | sed -E 's#.*/posts/([a-z-]+)/#\1#' | paste -sd,)
[ "$home_posts" = "latest-four,latest-three,standalone" ] && pass "home lists exactly the three latest posts, newest first" || fail "home lists exactly the three latest posts, newest first (got: $home_posts)"
avatar_file=$(ls "$ROOT"/static/images/avatar.* 2>/dev/null | head -1)
avatar_kb=$(( $(stat -c %s "$avatar_file") / 1024 ))
[ "$avatar_kb" -lt 200 ] && pass "avatar under 200 KB" || fail "avatar under 200 KB (${avatar_kb} KB)"

# Series
S=posts/rust-part-one/index.html
has $S 'Rust Intro</a> · Part 1 of 2' "series label shows name, part and total"
has $S 'href="?[^" >]*/series/rust-intro/' "series label links to series page"
has posts/rust-part-two/index.html 'Rust Intro</a> · Part 2 of 2' "part 2 label"
has $S 'href="?[^" >]*/posts/rust-part-two/[^>]*>[^<]*Next' "part 1 links to next part"
lacks $S 'Previous' "first part has no previous link"
has posts/rust-part-two/index.html 'href="?[^" >]*/posts/rust-part-one/[^>]*>[^<]*Previous' "part 2 links to previous part"
has $S '<details' "collapsed parts list present"
order=$(tr -d '\n' <"$OUT/$S" | grep -oE '<details.*</details>' | grep -oE 'Rust Part (One|Two)' | paste -sd,)
[ "$order" = "Rust Part One,Rust Part Two" ] && pass "parts ordered by part number not date" || fail "parts ordered by part number (got: $order)"
lacks $S 'Rust Part Three' "draft part absent from navigation and list"
exists series/rust-intro/index.html "series page exists"
has series/rust-intro/index.html 'A gentle introduction to Rust' "series page shows description"
has series/rust-intro/index.html '<h1[^>]*>Rust Intro</h1>' "series page shows title"
sorder=$(tr -d '\n' <"$OUT/series/rust-intro/index.html" | grep -oE 'Rust Part (One|Two|Three)' | paste -sd,)
[ "$sorder" = "Rust Part One,Rust Part Two" ] && pass "series page lists ordered published parts" || fail "series page order (got: $sorder)"
has posts/drafty-one/index.html 'Drafty Series</a> · Part 1 of 2' "draft part excluded from total"
lacks posts/drafty-one/index.html 'Drafty Two' "draft part absent from navigation"
lacks series/drafty/index.html 'Drafty Two' "draft part absent from series page"
lacks posts/standalone/index.html 'Part [0-9]+ of|<details' "post outside series has no series elements"
has posts/double-series/index.html 'Drafty Series</a> · Part 9 of' "first series value is used"
chk=$("$ROOT/scripts/check-series.sh" "$ROOT/tests/fixture/content" 2>&1)
echo "$chk" | grep -q 'double-series' && pass "multi-series post triggers warning" || fail "multi-series post triggers warning"
echo "$chk" | grep -q 'standalone\|rust-part-one' && fail "warning only for multi-series posts" || pass "warning only for multi-series posts"

has posts/name-series/index.html 'Name Test</a> · Part 1 of 1' "series referenced by display name resolves via slug"
has posts/name-series/index.html '<title>Name Series Post · IDrokin</title>' "post title includes site name"
has posts/name-series/index.html 'content="?Post description for meta"? name="?description' "post description used in meta"
has posts/name-series/index.html 'content="alpha, beta" name="?keywords' "post keywords emitted"
has posts/index.html 'content="?All fixture posts"? name="?description' "section description used in meta"
has index.html '<title>IDrokin</title>' "home title is the site name"
lacks posts/standalone/index.html 'name="?keywords' "no keywords meta without front matter keywords"
in_footer() { tr -d '\n' <"$OUT/index.html" | grep -oE '<footer.*</footer>' | grep -Eq -- "$1" && pass "$2" || fail "$2"; }
in_footer 'href="?https://github\.com/IDrokin117[" >]' "footer GitHub link comes from extra.github"
{ ! grep -q 'LyricalToxic' "$ROOT/config.toml"; } && pass "no stale GitHub identity in config" || fail "no stale GitHub identity in config"
# check-series: multi-line arrays and missing part
CS="$(mktemp -d)"; mkdir -p "$CS/posts"
printf '+++\ntitle = "A"\n[taxonomies]\nseries = [\n  "a",\n  "b",\n]\n[extra]\npart = 1\n+++\n' >"$CS/posts/multi.md"
printf '+++\ntitle = "B"\n[taxonomies]\nseries = ["a"]\n+++\n' >"$CS/posts/nopart.md"
printf '+++\ntitle = "C"\n[taxonomies]\nseries = ["a"]\n[extra]\npart = 2\n+++\n' >"$CS/posts/ok.md"
chk2=$("$ROOT/scripts/check-series.sh" "$CS" 2>&1); rc=$?
echo "$chk2" | grep -q 'multi.md' && pass "multi-line series array detected" || fail "multi-line series array detected"
echo "$chk2" | grep -q 'nopart.md' && pass "missing extra.part reported" || fail "missing extra.part reported"
echo "$chk2" | grep -q 'ok.md' && fail "valid post not reported" || pass "valid post not reported"
[ "$rc" -ne 0 ] && pass "check-series fails on missing part" || fail "check-series fails on missing part"
rm -rf "$CS"
"$ROOT/scripts/check-series.sh" "$ROOT/content" >/dev/null 2>&1 && pass "real content passes check-series" || fail "real content passes check-series"
grep -q 'check-series' "$ROOT/scripts/build.sh" && pass "build.sh runs check-series" || fail "build.sh runs check-series"
grep -q 'pull_request' "$ROOT/.github/workflows/zola.yml" && pass "CI runs on pull_request" || fail "CI runs on pull_request"

# Series discovery
posts_main=$(tr -d '\n' <"$OUT/posts/index.html" | grep -oE '<main[^>]*>.*</main>')
in_posts() { printf '%s' "$posts_main" | grep -Eq -- "$1" && pass "$2" || fail "$2"; }
nin_posts() { printf '%s' "$posts_main" | grep -Eq -- "$1" && fail "$2" || pass "$2"; }
in_posts 'href="?[^" >]*/series/rust-intro/[^>]*>Rust Intro<' "posts page lists Series linking to series page"
in_posts 'href="?[^" >]*/series/drafty/' "series with one published part is listed on posts page"
nin_posts 'All Draft Series|series/alldraft' "series with only draft parts not listed on posts page"
in_posts '<h2[^>]*>Series</h2>' "posts page has Series heading"
series_pos=$(printf '%s' "$posts_main" | grep -bo 'series/rust-intro' | head -1 | cut -d: -f1)
post_pos=$(printf '%s' "$posts_main" | grep -bo 'posts/standalone' | head -1 | cut -d: -f1)
[ -n "$series_pos" ] && [ -n "$post_pos" ] && [ "$series_pos" -lt "$post_pos" ] && pass "series listed before posts" || fail "series listed before posts"
in_home 'href="?[^" >]*/series/rust-intro/[^>]*>Rust Intro<' "home shows Series block with a Series"
printf '%s' "$home_main" | grep -Eq 'All Draft Series|series/alldraft' && fail "home omits all-draft series" || pass "home omits all-draft series"

# Variant: no Series at all
NS="$(mktemp -d)"
cp -r "$ROOT/config.toml" "$ROOT/templates" "$NS/"
[ -d "$ROOT/sass" ] && cp -r "$ROOT/sass" "$NS/"
[ -d "$ROOT/static" ] && cp -r "$ROOT/static" "$NS/"
cp -r "$ROOT/tests/fixture/content" "$NS/content"
find "$NS/content/series" -name '*.md' ! -name '_index.md' -delete
grep -lE '^series *=' "$NS"/content/posts/*.md | xargs rm -f
if "$ZOLA" --root "$NS" build --output-dir "$NS/public" >"$NS/build.log" 2>&1; then
  pass "no-series variant builds"
  for f in index.html posts/index.html; do
    grep -Eqi 'series' "$NS/public/$f" && fail "no-series variant: $f has no Series heading or links" || pass "no-series variant: $f has no Series heading or links"
  done
else
  cat "$NS/build.log"; fail "no-series variant builds"
fi
rm -rf "$NS"

# Tags and feed
exists tags/about/index.html "tag page exists"
has tags/about/index.html 'Hello World' "tag page lists its post"
exists rss.xml "RSS feed generated"
has rss.xml '<rss' "feed is RSS"
has posts/hello-world/index.html 'href="?[^" >]*/tags/about/' "post links to its tag"

# Search and comments removed
absent elasticlunr.min.js "no elasticlunr asset"
absent search_index.en.js "no search index"
absent js/search.js "no search script"
lacks index.html 'search|giscus' "no search or giscus markup on home"
lacks posts/hello-world/index.html 'search|giscus' "no search or giscus markup on post"

# Projects hidden
absent projects/index.html "no Projects page in built output"
absent projects/hidden/index.html "draft Project page not built"
lacks index.html 'projects' "no Projects link on home"
lacks posts/index.html 'projects' "no Projects link on posts list"
lacks rss.xml 'Hidden Project' "Projects not in feed"

# Per-page scripts
has posts/with-script/index.html '<script src="?[^" >]*/js/demo\.js' "page declaring a script loads it"
[ "$(grep -o '<script' "$OUT/posts/with-script/index.html" | wc -l)" -eq 1 ] && pass "scripted page loads only its own script" || fail "scripted page loads only its own script"
lacks posts/hello-world/index.html '<script' "page without script loads no scripts"
lacks index.html '<script' "home loads no scripts"

# Domain, theme, language
[ "$(cat "$ROOT/static/CNAME")" = "www.idrokin.com" ] && pass "CNAME unchanged" || fail "CNAME unchanged"
grep -q 'base_url = "https://www.idrokin.com/"' "$ROOT/config.toml" && pass "base_url unchanged" || fail "base_url unchanged"
{ ! grep -q pico "$ROOT/config.toml" && [ ! -e "$ROOT/.gitmodules" ] && [ ! -e "$ROOT/themes/pico" ]; } && pass "no pico theme, no submodule" || fail "no pico theme, no submodule"
exists style.css "single stylesheet compiled from sass"
absent css/responsive.css "no leftover pico css"
{ ! grep -rPq '[\x{0400}-\x{04FF}]' "$ROOT/templates" "$ROOT/config.toml" "$ROOT/tests/fixture/content"; } && pass "no Cyrillic in templates/config/fixture" || fail "no Cyrillic in templates/config/fixture"

# Typography and themes
exists fonts/source-serif-4-normal.woff2 "serif font served from the site"
exists fonts/source-serif-4-italic.woff2 "italic serif font served from the site"
lacks style.css 'https?://' "no third-party URLs in the stylesheet"
lacks index.html 'fonts\.(googleapis|gstatic)|https?://[^" ]*\.woff' "no third-party font requests in HTML"
has style.css 'prefers-color-scheme: ?dark' "dark theme follows system preference"
has style.css '@font-face' "fonts declared via @font-face"
lacks style.css 'data-theme' "no theme toggle"
has posts/hello-world/index.html 'class="?z-l-' "code highlighting is class-based"
lacks posts/hello-world/index.html 'style="[^"]*color:' "no inline highlight colors"
exists giallo-light.css "light highlight color set generated"
exists giallo-dark.css "dark highlight color set generated"
has posts/hello-world/index.html 'giallo-light.css[^>]*prefers-color-scheme: ?light|prefers-color-scheme: ?light[^>]*giallo-light.css' "light highlight set loaded for light scheme"
has posts/hello-world/index.html 'giallo-dark.css[^>]*prefers-color-scheme: ?dark|prefers-color-scheme: ?dark[^>]*giallo-dark.css' "dark highlight set loaded for dark scheme"
has index.html 'name="?viewport' "viewport meta for phone width"

echo
[ "$FAILS" -eq 0 ] && echo "all passed" || { echo "$FAILS failed"; exit 1; }
